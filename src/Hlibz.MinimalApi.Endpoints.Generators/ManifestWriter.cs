using System.Text;

using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace Hlibz.MinimalApi.Endpoints.Generators;

/// <summary>
/// Writes the generated source: the assembly's <c>EndpointManifestAttribute</c> and the
/// attribute applied to the assembly.
/// </summary>
internal static class ManifestWriter
{
    private const string ManifestAttributeName =
        "Hlibz.MinimalApi.Endpoints.EndpointManifestAttribute";

    private const string Namespace = "Hlibz.MinimalApi.Endpoints.Generated";

    private const string Registration = "global::Hlibz.MinimalApi.Endpoints.EndpointRegistration";

    private static string GeneratorName => typeof(ManifestWriter).Assembly.GetName().Name;

    private static string GeneratorVersion =>
        typeof(ManifestWriter).Assembly.GetName().Version?.ToString() ?? "0.0.0.0";

    /// <summary>
    /// The manifest class's name for the assembly being compiled, unique to it so assemblies that
    /// see each other's internals don't clash, or <see langword="null"/> when the compilation
    /// doesn't reference the library (nothing to generate).
    /// </summary>
    /// <param name="compilation">The compilation.</param>
    /// <returns>The class name, or <see langword="null"/>.</returns>
    public static string? ClassNameFor(Compilation compilation)
    {
        if (compilation.GetTypeByMetadataName(ManifestAttributeName) is null)
        {
            return null;
        }

        StringBuilder name = new("EndpointManifest_");
        foreach (char character in compilation.AssemblyName ?? "Assembly")
        {
            name.Append(char.IsLetterOrDigit(character) ? character : '_');
        }

        return name.ToString();
    }

    /// <summary>
    /// Writes the manifest.
    /// </summary>
    /// <param name="className">The manifest class's name.</param>
    /// <param name="endpoints">The endpoints to list, in order.</param>
    /// <returns>The source.</returns>
    public static string Write(string className, IEnumerable<EndpointModel> endpoints)
    {
        StringBuilder source = new();
        source.Append(
            $$"""
            // <auto-generated/>
            #nullable enable
            // Obsolete endpoints are still mapped.
            #pragma warning disable CS0612, CS0618

            [assembly: global::{{Namespace}}.{{className}}]

            namespace {{Namespace}}
            {
                /// <summary>
                /// The endpoints the Hlibz.MinimalApi.Endpoints source generator found in this
                /// assembly, read by EndpointDiscovery.
                /// </summary>
                [global::System.CodeDom.Compiler.GeneratedCode("{{GeneratorName}}", "{{GeneratorVersion}}")]
                internal sealed class {{className}} : global::{{ManifestAttributeName}}
                {
                    private static readonly {{Registration}}[] All =
                    {

            """);

        foreach (EndpointModel endpoint in endpoints)
        {
            string description = endpoint.Description is null
                ? "null"
                : SymbolDisplay.FormatLiteral(endpoint.Description, quote: true);
            source.Append(
                $$"""
                            new {{Registration}}(
                                typeof({{endpoint.TypeName}}),
                                static () => new {{endpoint.TypeName}}(),
                                typeof({{endpoint.GroupTypeName}}),
                                static () => new {{endpoint.GroupTypeName}}(),
                                {{description}}),

                """);
        }

        source.Append(
            $$"""
                    };

                    /// <inheritdoc/>
                    public override global::System.Collections.Generic.IReadOnlyList<{{Registration}}> Endpoints => All;
                }
            }

            """);
        return source.ToString();
    }
}
